"""Train and evaluate an SMS spam classifier using the official UCI dataset."""

from __future__ import annotations

import argparse
import csv
import io
from pathlib import Path
import urllib.request
import zipfile

import joblib
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DATA_FILE = DATA_DIR / "SMSSpamCollection"
MODEL_FILE = ROOT / "spam_classifier.joblib"
DATA_URL = "https://archive.ics.uci.edu/static/public/228/sms+spam+collection.zip"
LABELS = ["ham", "spam"]


def ensure_dataset() -> None:
    """Download the official UCI ZIP only when the dataset file is missing."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if DATA_FILE.exists():
        return

    print("Downloading the official UCI SMS Spam Collection...")
    try:
        request = urllib.request.Request(
            DATA_URL, headers={"User-Agent": "SWYNEX-AI-Problem-Design/1.0"}
        )
        with urllib.request.urlopen(request, timeout=60) as response:
            archive_bytes = response.read()
        with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
            member = next(
                name for name in archive.namelist()
                if Path(name).name == "SMSSpamCollection"
            )
            DATA_FILE.write_bytes(archive.read(member))
    except (OSError, StopIteration, zipfile.BadZipFile) as exc:
        raise RuntimeError(
            "Dataset download failed. Download the SMS Spam Collection from "
            "https://archive.ics.uci.edu/dataset/228/sms and place the extracted "
            "file named SMSSpamCollection inside the project's data folder."
        ) from exc


def load_dataset() -> pd.DataFrame:
    ensure_dataset()
    data = pd.read_csv(
        DATA_FILE,
        sep="\t",
        header=None,
        names=["label", "message"],
        quoting=csv.QUOTE_NONE,
        encoding="utf-8",
    ).dropna()
    data["label"] = data["label"].astype(str).str.strip().str.lower()
    data["message"] = data["message"].astype(str).str.strip()
    data = data[data["label"].isin(LABELS) & data["message"].ne("")]
    if data["label"].nunique() != 2:
        raise ValueError("Dataset must contain both ham and spam labels.")
    return data


def build_report(data, y_test, accuracy, report, matrix, sample_predictions) -> str:
    counts = data["label"].value_counts()
    lines = [
        "# SMS Spam Classifier — Evaluation Results",
        "",
        "> Metrics generated by running the model on the held-out test split. "
        "They are experiment results, not a guarantee of future performance.",
        "",
        "## Dataset",
        "",
        "- Source: [UCI SMS Spam Collection](https://archive.ics.uci.edu/dataset/228/sms)",
        "- Citation: Almeida, T. & Hidalgo, J. (2011). "
        "[UCI Machine Learning Repository](https://doi.org/10.24432/C5CC84).",
        "- License: CC BY 4.0 (attribution required).",
        f"- Total usable messages: **{len(data):,}**",
        f"- Ham messages: **{int(counts.get('ham', 0)):,}**",
        f"- Spam messages: **{int(counts.get('spam', 0)):,}**",
        "- Split: stratified 80% train / 20% test; random_state=42.",
        "",
        "## Method",
        "",
        "- Text features: TF-IDF using TfidfVectorizer with English stop words.",
        "- Classifier: Multinomial Naive Bayes.",
        "",
        "## Overall result",
        "",
        f"- Test messages: **{len(y_test):,}**",
        f"- Accuracy: **{accuracy:.4f} ({accuracy * 100:.2f}%)**",
        "",
        "## Classification report",
        "",
        "| Class | Precision | Recall | F1-score | Support |",
        "|---|---:|---:|---:|---:|",
    ]
    for label in LABELS:
        item = report[label]
        lines.append(
            f"| {label} | {item['precision']:.4f} | {item['recall']:.4f} | "
            f"{item['f1-score']:.4f} | {int(item['support'])} |"
        )
    lines.extend([
        "",
        "## Confusion matrix",
        "",
        "Rows are actual labels and columns are predicted labels; order is ham, spam.",
        "",
        "| Actual / Predicted | Ham | Spam |",
        "|---|---:|---:|",
        f"| Ham | {int(matrix[0][0])} | {int(matrix[0][1])} |",
        f"| Spam | {int(matrix[1][0])} | {int(matrix[1][1])} |",
        "",
        "## Example predictions",
        "",
    ])
    for message, predicted in sample_predictions:
        safe_message = message.replace("|", "\\|").replace("\n", " ")
        lines.append(f"- **{predicted.upper()}** — {safe_message}")
    lines.extend([
        "",
        "## Limitations",
        "",
        "- The dataset is historical and contains English-language SMS examples.",
        "- Performance may be weaker on newer scams, Tamil messages, or code-mixed text.",
        "- A false positive can flag a legitimate message; a false negative can miss spam.",
        "- This is a learning prototype, not a production security filter. It should not "
        "automatically delete or block messages.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Train and evaluate the SMS spam classifier.")
    parser.add_argument(
        "--no-interactive",
        action="store_true",
        help="Skip the final prompt (used by automated CI runs).",
    )
    parser.add_argument(
        "--report-path",
        default="reports/evaluation.md",
        help="Path where the measured Markdown evaluation report is written.",
    )
    args = parser.parse_args()

    data = load_dataset()
    X_train, X_test, y_train, y_test = train_test_split(
        data["message"], data["label"],
        test_size=0.20, random_state=42, stratify=data["label"]
    )
    model = Pipeline([
        ("tfidf", TfidfVectorizer(stop_words="english")),
        ("classifier", MultinomialNB()),
    ])
    model.fit(X_train, y_train)
    predictions = model.predict(X_test)

    accuracy = accuracy_score(y_test, predictions)
    report_text = classification_report(y_test, predictions, labels=LABELS, zero_division=0)
    report_dict = classification_report(
        y_test, predictions, labels=LABELS, output_dict=True, zero_division=0
    )
    matrix = confusion_matrix(y_test, predictions, labels=LABELS)

    examples = [
        "Congratulations! You have won a free prize. Call now!",
        "Hi, are we still meeting for lunch today?",
    ]
    example_predictions = [(message, model.predict([message])[0]) for message in examples]

    print("\n=== SMS SPAM CLASSIFICATION RESULTS ===")
    print(f"Total records: {len(data)}")
    print(f"Training records: {len(X_train)}")
    print(f"Test records: {len(X_test)}")
    print(f"Accuracy: {accuracy:.4f} ({accuracy * 100:.2f}%)")
    print("\nClassification report:")
    print(report_text)
    print("Confusion matrix (rows = actual, columns = predicted; order: ham, spam):")
    print(matrix)
    print("\nExample predictions:")
    for message, predicted in example_predictions:
        print(f"{predicted.upper()}: {message}")

    report_path = (ROOT / args.report_path).resolve()
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(
        build_report(data, y_test, accuracy, report_dict, matrix, example_predictions),
        encoding="utf-8",
    )
    joblib.dump(model, MODEL_FILE)
    print(f"\nEvaluation report saved to: {report_path.relative_to(ROOT)}")
    print(f"Trained model saved to: {MODEL_FILE.name}")

    if not args.no_interactive:
        print("\nEnter an SMS message to test (or press Enter to finish):")
        message = input("> ").strip()
        if message:
            print("Prediction:", model.predict([message])[0].upper())
            print("Reminder: this is a learning prototype, not a guarantee that a message is safe.")


if __name__ == "__main__":
    main()
